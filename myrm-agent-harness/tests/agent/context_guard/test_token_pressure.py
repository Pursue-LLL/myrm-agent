"""The token-pressure estimate: exact character weights, and its distance from real token counts.

The estimate is a proxy that decides when a pasted text is parked in a file, so what matters is how far it
can fall below the real count. The samples are generated by recipe (no random data) and compared with counts
recorded once under tiktoken ``o200k_base``; the test itself does not tokenize.
"""

from __future__ import annotations

import base64
import hashlib
import json
from collections.abc import Callable

import pytest

from myrm_agent_harness.agent.context_guard import estimate_token_pressure

_SAMPLE_CHARS = 8_000


@pytest.mark.parametrize(
    ("char", "centi_weight"),
    [
        ("a", 25),
        (" ", 25),
        ("\n", 25),
        ("A", 100),
        ("7", 75),
        ("{", 40),
        ("\x00", 40),
        ("é", 50),
        ("я", 50),
        ("ก", 50),
        ("字", 180),
        ("あ", 180),
        ("한", 180),
        ("，", 180),
        ("😀", 180),
    ],
)
def test_each_kind_of_character_weighs_its_own_amount(char: str, centi_weight: int) -> None:
    assert estimate_token_pressure(char * 1_000) == centi_weight * 10


def test_the_weights_are_summed_before_they_are_rounded_down() -> None:
    assert estimate_token_pressure("") == 0
    assert estimate_token_pressure("aaa") == 0
    assert estimate_token_pressure("字") == 1
    # 100 of each of lowercase, upper case, digit, symbol, space, other alphabet and wide: (25+100+75+40+25+50+180) * 100 / 100.
    assert (
        estimate_token_pressure("a" * 100 + "A" * 100 + "1" * 100 + "{" * 100 + " " * 100 + "я" * 100 + "字" * 100)
        == 495
    )


def _chain(seed: str) -> Callable[[], bytes]:
    state = seed.encode()

    def step() -> bytes:
        nonlocal state
        state = hashlib.sha256(state).digest()
        return state

    return step


def _repeat(unit: str) -> str:
    return (unit * (_SAMPLE_CHARS // len(unit) + 1))[:_SAMPLE_CHARS]


def _hex() -> str:
    step = _chain("hex")
    return "".join(step().hex() for _ in range(_SAMPLE_CHARS // 64 + 1))[:_SAMPLE_CHARS]


def _base64() -> str:
    step = _chain("base64")
    return base64.b64encode(b"".join(step() for _ in range(_SAMPLE_CHARS // 32 + 1))).decode()[:_SAMPLE_CHARS]


def _digest(i: int, length: int) -> str:
    return hashlib.sha256(str(i).encode()).hexdigest()[:length]


def _log_lines() -> str:
    lines = (
        f"2026-10-27T15:{i % 60:02d}:{i * 7 % 60:02d}.{i * 37 % 1000:03d}Z INFO req={_digest(i, 12)}"
        f" path=/api/v1/x/{i * 7919 % 100_000} status=200 ms={i * 13 % 900}\n"
        for i in range(_SAMPLE_CHARS // 60)
    )
    return "".join(lines)[:_SAMPLE_CHARS]


def _urls() -> str:
    lines = (
        f"https://example.com/a/{_digest(i, 10)}/b?id={i * 7919 % 1_000_000}&t={i * 31 % 4096:x}\n"
        for i in range(_SAMPLE_CHARS // 50)
    )
    return "".join(lines)[:_SAMPLE_CHARS]


def _minified_json() -> str:
    rows = [{"id": 100_000_000 + i * 7919, "v": round(i * 1.618 % 1000, 3), "k": _digest(i, 8)} for i in range(400)]
    return json.dumps(rows, separators=(",", ":"))[:_SAMPLE_CHARS]


_SAMPLES: dict[str, Callable[[], str]] = {
    "english_prose": lambda: _repeat(
        "The quick brown fox jumps over the lazy dog while the committee reviews the quarterly budget "
        "and schedules a follow-up meeting. "
    ),
    "python_code": lambda: _repeat(
        "def handle(self, payload: dict[str, int]) -> int:\n"
        "    total = sum(v for k, v in payload.items() if k.startswith('n_'))\n"
        "    return total\n\n"
    ),
    "stack_trace": lambda: _repeat(
        'Traceback (most recent call last):\n  File "/srv/app/main.py", line 128, in handle\n'
        "    result = await service.run(payload)\nValueError: bad value: 'x'\n"
    ),
    "log_lines": _log_lines,
    "urls": _urls,
    "minified_json": _minified_json,
    "hex": _hex,
    "base64": _base64,
    "chinese": lambda: _repeat("敏捷的棕色狐狸跳过了懒惰的狗，同时委员会审查季度预算并安排下一次会议。"),
    "japanese": lambda: _repeat("素早い茶色の狐が怠け者の犬を飛び越え、その間に委員会は四半期予算を審査します。"),
    "russian": lambda: _repeat(
        "Быстрая коричневая лиса прыгает через ленивую собаку, пока комитет рассматривает квартальный бюджет. "
    ),
    "arabic": lambda: _repeat("الثعلب البني السريع يقفز فوق الكلب الكسول بينما تراجع اللجنة الميزانية الفصلية. "),
    "hindi": lambda: _repeat("तेज़ भूरी लोमड़ी आलसी कुत्ते के ऊपर कूदती है जबकि समिति तिमाही बजट की समीक्षा करती है। "),
    "thai": lambda: _repeat("สุนัขจิ้งจอกสีน้ำตาลกระโดดข้ามสุนัขขี้เกียจในขณะที่คณะกรรมการตรวจสอบงบประมาณรายไตรมาส "),
}

# Real token counts of each sample under tiktoken (0.14) ``o200k_base``, recorded once.
_O200K_TOKENS: dict[str, int] = {
    "arabic": 2401,
    "base64": 5476,
    "chinese": 6402,
    "english_prose": 1439,
    "hex": 4565,
    "hindi": 2851,
    "japanese": 7590,
    "log_lines": 3812,
    "minified_json": 3651,
    "python_code": 2219,
    "russian": 2142,
    "stack_trace": 2148,
    "thai": 4186,
    "urls": 3382,
}

# The estimate may be above the real count (a text is then parked early) but must not fall far below it: that is
# how a text slips past the guard. The lower bound only catches an estimate that has grown out of proportion.
_MIN_REAL_TO_ESTIMATE = 0.4
_MAX_REAL_TO_ESTIMATE = 1.3


@pytest.mark.parametrize("name", sorted(_SAMPLES))
def test_the_estimate_stays_within_a_band_of_the_real_token_count(name: str) -> None:
    sample = _SAMPLES[name]()
    assert len(sample) == _SAMPLE_CHARS

    ratio = _O200K_TOKENS[name] / estimate_token_pressure(sample)

    assert _MIN_REAL_TO_ESTIMATE <= ratio <= _MAX_REAL_TO_ESTIMATE, f"{name}: real/estimate = {ratio:.2f}"
