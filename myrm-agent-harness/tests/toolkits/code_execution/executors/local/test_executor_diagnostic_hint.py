"""Tests for LocalExecutor error diagnostics via ExecutionResult.error_hint.

Hints are generated by ExecutionResult.__post_init__ (models.py) — not by the
executor itself — so these tests verify the integrated pipeline: execute() →
ExecutionResult auto-classification → error_hint populated.
"""

from unittest.mock import patch

import pytest

from myrm_agent_harness.toolkits.code_execution.config import ExecutionConfig
from myrm_agent_harness.toolkits.code_execution.executors.local.executor import LocalExecutor
from myrm_agent_harness.toolkits.code_execution.executors.models import ExecutionContext
from tests.support.fake_process import FakeProcess


@pytest.mark.asyncio
async def test_local_executor_module_not_found_uses_error_hint():
    """ModuleNotFoundError → error_category='import' + error_hint with install command."""
    executor = LocalExecutor(ExecutionConfig())
    context = ExecutionContext(session_id="test_session", code="import requests")

    with patch(
        "myrm_agent_harness.toolkits.code_execution.executors.local.executor.asyncio.create_subprocess_exec"
    ) as mock_exec:
        mock_exec.return_value = FakeProcess(
            stdout=b"",
            stderr=b"Traceback (most recent call last):\nModuleNotFoundError: No module named 'requests'",
            returncode=1,
        )

        result = await executor.execute(context)

        assert not result.success
        assert result.error_category == "import"
        assert result.error_hint is not None
        assert "requests" in result.error_hint
        assert "install" in result.error_hint


