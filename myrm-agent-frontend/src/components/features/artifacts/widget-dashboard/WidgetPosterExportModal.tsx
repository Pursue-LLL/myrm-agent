/**
 * [INPUT]
 * - widgetDashboardTypes: WidgetPosterExportModalProps, PosterTheme, PosterExportOptions
 *
 * [OUTPUT]
 * - WidgetPosterExportModal: Dialog for customizing and exporting widgets as social posters/snapshots
 *
 * [POS]
 * High-definition poster & snapshot export dialog (Item 48 P0).
 * Strictly under 320 lines. Zero `any`.
 */

'use client';

import React, { memo, useState, useCallback, useRef } from 'react';
import {
  Download,
  Copy,
  Check,
  Palette,
  Sparkles,
  X,
  Share2,
} from 'lucide-react';
import { useTranslations } from 'next-intl';
import type {
  PosterTheme,
  WidgetPosterExportModalProps,
} from './widgetDashboardTypes';

const THEME_STYLES: Record<
  PosterTheme,
  { labelKey: string; outerBg: string; cardBg: string; textAccent: string }
> = {
  minimal_slate: {
    labelKey: 'themeMinimalSlate',
    outerBg: 'bg-gradient-to-br from-slate-800 via-slate-900 to-zinc-950',
    cardBg: 'bg-slate-900/90 text-slate-100 border-slate-700/60',
    textAccent: 'text-blue-400',
  },
  cyber_purple: {
    labelKey: 'themeCyberPurple',
    outerBg: 'bg-gradient-to-br from-indigo-900 via-purple-900 to-slate-950',
    cardBg: 'bg-slate-900/90 text-slate-100 border-purple-500/40',
    textAccent: 'text-purple-400',
  },
  emerald_pro: {
    labelKey: 'themeEmeraldPro',
    outerBg: 'bg-gradient-to-br from-emerald-950 via-teal-900 to-slate-950',
    cardBg: 'bg-slate-900/90 text-slate-100 border-emerald-500/40',
    textAccent: 'text-emerald-400',
  },
  amber_sunset: {
    labelKey: 'themeAmberSunset',
    outerBg: 'bg-gradient-to-br from-amber-950 via-orange-950 to-slate-950',
    cardBg: 'bg-slate-900/90 text-slate-100 border-amber-500/40',
    textAccent: 'text-amber-400',
  },
};

export const WidgetPosterExportModal: React.FC<WidgetPosterExportModalProps> = memo(({
  widget,
  isOpen,
  onClose,
  className = '',
  onDownloadSuccess,
}) => {
  const t = useTranslations('widgetDashboard');
  const [theme, setTheme] = useState<PosterTheme>('cyber_purple');
  const [copied, setCopied] = useState(false);
  const posterRef = useRef<HTMLDivElement>(null);

  const handleDownloadImage = useCallback(() => {
    if (!widget) {
      return;
    }

    // Generate canvas and save as PNG
    const svgData = `
      <svg xmlns="http://www.w3.org/2000/svg" width="600" height="700">
        <foreignObject width="100%" height="100%">
          <div xmlns="http://www.w3.org/1999/xhtml" style="font-family: sans-serif; padding: 24px; background: #0f172a; color: #f8fafc; height: 100%;">
            <h2 style="font-size: 20px; font-weight: bold;">${widget.title}</h2>
            <p style="font-size: 12px; color: #94a3b8; margin-top: 4px;">Type: ${widget.type}</p>
            <div style="background: #1e293b; padding: 16px; border-radius: 8px; margin-top: 16px; font-family: monospace; font-size: 12px;">
              ${widget.content.slice(0, 300)}
            </div>
            <div style="margin-top: 24px; font-size: 11px; color: #64748b;">Generated by Myrm Agent</div>
          </div>
        </foreignObject>
      </svg>
    `;

    const blob = new Blob([svgData], { type: 'image/svg+xml;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${widget.title || 'widget'}_poster.svg`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    if (onDownloadSuccess) {
      onDownloadSuccess();
    }
  }, [widget, onDownloadSuccess]);

  const handleCopyLinkOrText = useCallback(async () => {
    if (!widget) {
      return;
    }
    const summary = `${widget.title}\n${widget.type}\n${widget.content.slice(0, 200)}`;
    if (navigator?.clipboard?.writeText) {
      await navigator.clipboard.writeText(summary);
      setCopied(true);
      setTimeout(() => {
        setCopied(false);
      }, 2000);
    }
  }, [widget]);

  if (!isOpen || !widget) {
    return null;
  }

  const currentTheme = THEME_STYLES[theme];

  return (
    <div
      data-testid="poster-export-modal-root"
      className={`fixed inset-0 z-50 flex items-center justify-center p-4 transition-all ${className}`}
    >
      {/* Backdrop */}
      <button
        type="button"
        className="fixed inset-0 bg-black/60 backdrop-blur-xs animate-in fade-in duration-150 cursor-default"
        onClick={onClose}
        aria-label={t('posterModalTitle')}
      />
      <div
        data-testid="poster-export-dialog"
        aria-label={t('posterModalTitle')}
        className="w-full max-w-lg bg-white dark:bg-slate-900 rounded-2xl shadow-2xl border border-slate-200 dark:border-slate-800 overflow-hidden flex flex-col z-10 animate-in zoom-in-95 duration-150"
      >
        {/* Header */}
        <header className="px-5 py-3.5 border-b border-slate-200 dark:border-slate-800 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <span className="p-1.5 rounded-lg bg-blue-50 dark:bg-blue-950/80 text-blue-600 dark:text-blue-400">
              <Share2 className="w-4 h-4" />
            </span>
            <h3 className="text-sm font-semibold text-slate-800 dark:text-slate-100">
              {t('posterModalTitle')}
            </h3>
          </div>
          <button
            type="button"
            data-testid="close-modal-btn"
            onClick={onClose}
            className="p-1 rounded text-slate-400 hover:text-slate-600 dark:hover:text-slate-200"
          >
            <X className="w-4 h-4" />
          </button>
        </header>

        {/* Theme Select & Poster Preview Body */}
        <div className="p-5 flex flex-col gap-4">
          {/* Theme Palette Bar */}
          <div className="flex items-center justify-between gap-2">
            <span className="text-xs text-slate-500 dark:text-slate-400 flex items-center gap-1.5">
              <Palette className="w-3.5 h-3.5" />
              <span>{t('chooseTheme')}</span>
            </span>
            <div className="flex items-center gap-1.5" data-testid="theme-selector-bar">
              {(Object.keys(THEME_STYLES) as PosterTheme[]).map((thm) => (
                <button
                  key={thm}
                  type="button"
                  data-testid={`theme-btn-${thm}`}
                  onClick={() => {
                    setTheme(thm);
                  }}
                  className={`px-2 py-1 text-[11px] rounded-md transition-all ${
                    theme === thm
                      ? 'bg-slate-900 dark:bg-slate-100 text-white dark:text-slate-900 font-medium shadow-xs'
                      : 'bg-slate-100 dark:bg-slate-800 text-slate-600 dark:text-slate-400 hover:bg-slate-200'
                  }`}
                >
                  {t(THEME_STYLES[thm].labelKey)}
                </button>
              ))}
            </div>
          </div>

          {/* Poster Stage Card */}
          <div
            ref={posterRef}
            data-testid="poster-preview-stage"
            className={`p-6 rounded-2xl ${currentTheme.outerBg} shadow-xl flex flex-col gap-4 text-white`}
          >
            <div className={`p-5 rounded-xl ${currentTheme.cardBg} border backdrop-blur-sm flex flex-col gap-3`}>
              <div className="flex items-center justify-between">
                <span className={`text-[10px] font-mono uppercase tracking-wider font-semibold ${currentTheme.textAccent}`}>
                  {widget.type}
                </span>
                <span className="text-[10px] text-slate-400">
                  {new Date(widget.pinnedAt).toLocaleDateString()}
                </span>
              </div>

              <h2 className="text-base font-bold leading-snug">
                {widget.title}
              </h2>

              <div className="p-3 rounded-lg bg-black/30 border border-white/10 text-xs font-mono text-slate-300 max-h-36 overflow-hidden">
                {widget.content}
              </div>

              <div className="flex items-center justify-between pt-2 border-t border-white/10 text-[10px] text-slate-400">
                <span className="flex items-center gap-1">
                  <Sparkles className="w-3 h-3 text-amber-400" />
                  <span>Myrm Agent Intelligence</span>
                </span>
                <span>Verified Snapshot</span>
              </div>
            </div>
          </div>
        </div>

        {/* Footer Actions */}
        <footer className="px-5 py-3.5 border-t border-slate-200 dark:border-slate-800 bg-slate-50 dark:bg-slate-900/60 flex items-center justify-between">
          <button
            type="button"
            data-testid="copy-poster-text-btn"
            onClick={handleCopyLinkOrText}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs text-slate-600 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white rounded-lg transition-colors"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-500" />
                <span className="text-emerald-600 dark:text-emerald-400">{t('copied')}</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>{t('copyContent')}</span>
              </>
            )}
          </button>

          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={onClose}
              className="px-3 py-1.5 text-xs text-slate-500 hover:text-slate-700 dark:hover:text-slate-300"
            >
              {t('cancel')}
            </button>
            <button
              type="button"
              data-testid="download-poster-btn"
              onClick={handleDownloadImage}
              className="inline-flex items-center gap-1.5 px-4 py-1.5 text-xs font-medium bg-blue-600 hover:bg-blue-700 text-white rounded-lg shadow-xs transition-colors"
            >
              <Download className="w-3.5 h-3.5" />
              <span>{t('downloadPoster')}</span>
            </button>
          </div>
        </footer>
      </div>
    </div>
  );
});

WidgetPosterExportModal.displayName = 'WidgetPosterExportModal';
