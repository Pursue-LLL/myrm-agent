"""Dev Gate contract SSOT for Chrome MCP E2E orchestration: error tokens, parallel caps and timeout budgets.

The contract is a package of layers; a layer imports only the layers before it in this order: catalog, caps, wall_clock,
parallel_pressure, mux, attach, evaluate, admission, open_page, transport_stall, pytest_timeouts, pytest_argv.

This module re-exports every name that code outside the package reads. A patch reaches only the readers of the module it
is applied to. Outside code reads a name from here at call time (`from dev_gate.contract import X` inside the function), so
a test patches `dev_gate.contract.X`. Layers read the pressure readings through `dev_gate.contract.parallel_pressure`
(not re-exported here), so a test patches `dev_gate.contract.parallel_pressure.<name>`. A name that one layer reads for
itself (`attach._host_load_ratio`, `transport_stall._backend_only_ensure_parallel_load`,
`pytest_timeouts.parallel_live_pytest_timeout_floor_sec`) is patched on that layer.

importlib.reload(dev_gate.contract) reloads the layers first, lowest first, so every budget is recomputed from the current
environment and sources.
"""

