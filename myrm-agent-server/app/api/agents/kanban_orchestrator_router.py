"""FastAPI endpoints for Visual Multi-Agent Kanban Orchestrator and Card Lifecycle Dispatcher."""

from __future__ import annotations

from typing import List

from fastapi import APIRouter, Depends, HTTPException, status
from myrm_agent_harness.agent.sub_agents.kanban_orchestrator import (
    KanbanBlockedCardError,
    KanbanCardNotFoundError,
    KanbanDependencyCycleError,
)

from app.schemas.kanban_orchestrator import (
    CardArtifactDTO,
    CreateBoardRequestDTO,
    CreateCardRequestDTO,
    DecomposeGoalRequestDTO,
    DecomposeGoalResponseDTO,
    HumanOverrideRequestDTO,
    KanbanBoardStateDTO,
    KanbanCardDTO,
    MountArtifactRequestDTO,
    TransitionCardRequestDTO,
    TransitionCardResponseDTO,
)
from app.services.agent.kanban_orchestrator_service import (
    KanbanOrchestratorService,
    get_kanban_orchestrator_service,
)

router = APIRouter(prefix="/agents/kanban-orchestrator", tags=["kanban-orchestrator"])


@router.get(
    "/boards",
    response_model=List[KanbanBoardStateDTO],
    summary="List all active multi-agent Kanban boards",
)
def list_boards(
    service: KanbanOrchestratorService = Depends(get_kanban_orchestrator_service),
) -> List[KanbanBoardStateDTO]:
    """Retrieve list of all active project boards."""
    return service.list_boards()


@router.post(
    "/boards",
    response_model=KanbanBoardStateDTO,
    status_code=status.HTTP_201_CREATED,
    summary="Create a new persistent project Kanban board",
)
def create_board(
    req: CreateBoardRequestDTO,
    service: KanbanOrchestratorService = Depends(get_kanban_orchestrator_service),
) -> KanbanBoardStateDTO:
    """Initialize a multi-agent Kanban board bound to a session."""
    return service.create_board(req)


@router.get(
    "/boards/{board_id}",
    response_model=KanbanBoardStateDTO,
    summary="Get board state with all swimlanes and cards",
)
def get_board(
    board_id: str,
    service: KanbanOrchestratorService = Depends(get_kanban_orchestrator_service),
) -> KanbanBoardStateDTO:
    """Retrieve a project board by ID."""
    try:
        return service.get_board(board_id)
    except KanbanCardNotFoundError as err:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=str(err),
        ) from err


@router.post(
    "/boards/{board_id}/cards",
    response_model=KanbanCardDTO,
    status_code=status.HTTP_201_CREATED,
    summary="Create a new task card with DAG dependency checks and sandbox allocation",
)
def create_card(
    board_id: str,
    req: CreateCardRequestDTO,
    service: KanbanOrchestratorService = Depends(get_kanban_orchestrator_service),
) -> KanbanCardDTO:
    """Create task card with automatic dependency calculation and card-scoped sandbox assignment."""
    try:
        return service.create_card(board_id=board_id, req=req)
    except KanbanCardNotFoundError as err:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=str(err),
        ) from err
    except KanbanDependencyCycleError as err:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(err),
        ) from err


@router.post(
    "/boards/{board_id}/cards/{card_id}/transition",
    response_model=TransitionCardResponseDTO,
    summary="Transition card to a target lane with auto-unblock cascade",
)
def transition_card(
    board_id: str,
    card_id: str,
    req: TransitionCardRequestDTO,
    service: KanbanOrchestratorService = Depends(get_kanban_orchestrator_service),
) -> TransitionCardResponseDTO:
    """Move card between swimlanes and automatically unlock downstream cards upon completion."""
    try:
        return service.transition_card(board_id=board_id, card_id=card_id, req=req)
    except KanbanCardNotFoundError as err:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=str(err),
        ) from err
    except KanbanBlockedCardError as err:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=str(err),
        ) from err


@router.post(
    "/boards/{board_id}/cards/{card_id}/artifacts",
    response_model=CardArtifactDTO,
    status_code=status.HTTP_201_CREATED,
    summary="Mount an execution output artifact to a card",
)
def mount_artifact(
    board_id: str,
    card_id: str,
    req: MountArtifactRequestDTO,
    service: KanbanOrchestratorService = Depends(get_kanban_orchestrator_service),
) -> CardArtifactDTO:
    """Mount diff, file, or report artifact generated by the assigned specialist."""
    try:
        return service.mount_artifact(board_id=board_id, card_id=card_id, req=req)
    except KanbanCardNotFoundError as err:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=str(err),
        ) from err


@router.post(
    "/boards/{board_id}/cards/{card_id}/override",
    response_model=TransitionCardResponseDTO,
    summary="Human-in-the-loop override for agent reassignment, priority shift, or drag-and-drop",
)
def human_override(
    board_id: str,
    card_id: str,
    req: HumanOverrideRequestDTO,
    service: KanbanOrchestratorService = Depends(get_kanban_orchestrator_service),
) -> TransitionCardResponseDTO:
    """Allow human user to intervene, reassign specialist agent, or override card priority/lane."""
    try:
        return service.human_override(board_id=board_id, card_id=card_id, req=req)
    except KanbanCardNotFoundError as err:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=str(err),
        ) from err
    except KanbanBlockedCardError as err:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=str(err),
        ) from err


@router.post(
    "/boards/{board_id}/decompose",
    response_model=DecomposeGoalResponseDTO,
    status_code=status.HTTP_201_CREATED,
    summary="Boss Agent (Orchestrator) automated goal decomposition into sequenced DAG task cards",
)
def decompose_goal(
    board_id: str,
    req: DecomposeGoalRequestDTO,
    service: KanbanOrchestratorService = Depends(get_kanban_orchestrator_service),
) -> DecomposeGoalResponseDTO:
    """Decompose project mission into sequenced task cards with dependencies and specialist assignment."""
    try:
        return service.decompose_goal(board_id=board_id, req=req)
    except KanbanCardNotFoundError as err:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=str(err),
        ) from err
