"""Service for client-side secret leak scanning and BFF auto-refactoring.

[POS]
Integrates harness security tools into server-level diagnostics.
Provides audit scans and automated BFF remediation suggestions for WebUI / developers.
"""

from __future__ import annotations

import logging

from myrm_agent_harness.toolkits.code_execution.security.bff_refactor import (
    BffAutoRefactorEngine,
    BffRefactorResult,
)
from myrm_agent_harness.toolkits.code_execution.security.client_secret_scanner import (
    ClientSideSecretScanner,
)
from pydantic import BaseModel, Field

logger = logging.getLogger(__name__)


class SecretFindingSchema(BaseModel):
    """Schema representing a detected secret finding."""

    secret_type: str = Field(..., description="Category of detected secret, e.g. OpenAI Key, Database URL")
    pattern_name: str = Field(..., description="Pattern identifier")
    line_number: int = Field(..., description="1-indexed line number in source code")
    matched_snippet: str = Field(..., description="Masked snippet preview")
    suggested_env_var: str = Field(..., description="Suggested environment variable key")
    file_path: str = Field(..., description="Source code file path")


class ClientSecretScanReport(BaseModel):
    """Report summarizing secret leak inspection on client code."""

    file_path: str = Field(..., description="Target file inspected")
    is_client_code: bool = Field(..., description="Whether file is classified as browser-facing code")
    has_leak: bool = Field(..., description="True if one or more hardcoded secrets were detected")
    findings_count: int = Field(..., description="Total violations found")
    findings: list[SecretFindingSchema] = Field(default_factory=list, description="List of findings")


class BffRefactorResponseSchema(BaseModel):
    """Refactoring suggestions generated by the BFF engine."""

    original_file_path: str = Field(..., description="Target client code file path")
    refactored_client_code: str = Field(..., description="Remediated client code with secrets replaced")
    extracted_env_entries: dict[str, str] = Field(default_factory=dict, description="Extracted env key-values")
    suggested_env_file_content: str = Field(..., description="Ready-to-paste .env content")
    server_proxy_file_path: str = Field(..., description="Target path for server-side proxy route")
    server_proxy_code: str = Field(..., description="Server route handler code (Next.js / Node.js)")
    refactor_explanation: str = Field(..., description="Explanation of remediation steps")


class ClientSecretGuardService:
    """Service providing secret scanning and BFF remediation capabilities."""

    @classmethod
    def scan_client_code(cls, code: str, file_path: str) -> ClientSecretScanReport:
        """Scan source code for hardcoded secrets."""
        is_client = ClientSideSecretScanner.is_client_code_file(file_path)
        raw_findings = ClientSideSecretScanner.scan_code(code, file_path)

        findings = [
            SecretFindingSchema(
                secret_type=f.secret_type,
                pattern_name=f.pattern_name,
                line_number=f.line_number,
                matched_snippet=f.matched_snippet,
                suggested_env_var=f.suggested_env_var,
                file_path=f.file_path,
            )
            for f in raw_findings
        ]

        return ClientSecretScanReport(
            file_path=file_path,
            is_client_code=is_client,
            has_leak=len(findings) > 0,
            findings_count=len(findings),
            findings=findings,
        )

    @classmethod
    def refactor_to_bff(cls, code: str, file_path: str) -> BffRefactorResponseSchema:
        """Scan and automatically generate BFF refactored artifacts."""
        raw_findings = ClientSideSecretScanner.scan_code(code, file_path)
        refactor_res: BffRefactorResult = BffAutoRefactorEngine.refactor(code, file_path, raw_findings)

        return BffRefactorResponseSchema(
            original_file_path=refactor_res.original_file_path,
            refactored_client_code=refactor_res.refactored_client_code,
            extracted_env_entries=refactor_res.extracted_env_entries,
            suggested_env_file_content=refactor_res.suggested_env_file_content,
            server_proxy_file_path=refactor_res.server_proxy_file_path,
            server_proxy_code=refactor_res.server_proxy_code,
            refactor_explanation=refactor_res.refactor_explanation,
        )
