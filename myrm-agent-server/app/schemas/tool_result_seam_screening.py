"""
[POS] app/schemas/tool_result_seam_screening.py
[INPUT] pydantic
[OUTPUT] ScreeningVerdictStatusEnum, ScreeningEngineModeEnum, ToolResultScreenRequest, RedactedSpanDTO, ToolResultScreenResponse, SeamScreeningBatchRequest, SeamScreeningBatchResponse, SeamScreeningConfigUpdateDTO, SeamScreeningStatsResponse

Pydantic schemas for tool result seam screening and in-place redactor suite.

Strict typing applied: No `Any` types allowed.
"""

from __future__ import annotations

from enum import StrEnum

from pydantic import BaseModel, Field


class ScreeningVerdictStatusEnum(StrEnum):
    """Screening verdict status enumeration."""

    CLEAN = "clean"
    REDACTED = "redacted"
    FAIL_OPEN = "fail_open"
    BYPASS = "bypass"


class ScreeningEngineModeEnum(StrEnum):
    """Engine screening mode enumeration."""

    DUAL_MODE = "dual_mode"
    LOCAL_ONLY = "local_only"
    FAST_MODEL_ONLY = "fast_model_only"


class ToolResultScreenRequest(BaseModel):
    """Request payload for screening a single tool output at the physical seam."""

    tool_name: str = Field(..., min_length=1, max_length=100, description="Name of the executed tool.")
    tool_result: str = Field(..., description="Raw output generated by the tool before context injection.")
    fast_model_enabled: bool = Field(default=True, description="Whether to engage fast micro-model detection.")


class ToolResultScreenResponse(BaseModel):
    """Response containing screening results and the redacted content."""

    tool_name: str = Field(..., description="Name of the audited tool.")
    verdict_status: ScreeningVerdictStatusEnum = Field(..., description="Screening outcome verdict.")
    screening_mode: ScreeningEngineModeEnum = Field(..., description="Engine mode employed.")
    total_units: int = Field(..., ge=0, description="Total discrete paragraph/field units processed.")
    flagged_units: int = Field(..., ge=0, description="Count of units flagged for prompt injection.")
    flagged_chunk_ids: list[int] = Field(default_factory=list, description="IDs of redacted chunks.")
    redacted_content: str = Field(..., description="In-place sanitized tool output safe for LLM context.")
    latency_ms: float = Field(..., ge=0.0, description="Screening elapsed time in milliseconds.")
    reason: str = Field(default="", description="Diagnostic justification or degradation note.")
    scores: dict[int, float] = Field(default_factory=dict, description="Unit-level threat confidence scores.")


class BatchToolResultScreenRequest(BaseModel):
    """Request payload for batch screening multiple tool outputs."""

    items: list[ToolResultScreenRequest] = Field(..., min_length=1, max_length=50, description="Batch items.")


class BatchToolResultScreenResponse(BaseModel):
    """Consolidated response for batch screening."""

    results: list[ToolResultScreenResponse] = Field(..., description="List of individual screening verdicts.")
    total_screened: int = Field(..., ge=0, description="Total tool results screened.")
    total_redacted: int = Field(..., ge=0, description="Total tool results with in-place redactions.")
    aggregate_latency_ms: float = Field(..., ge=0.0, description="Sum of latencies across batch.")


class ScreeningPolicyUpdateRequest(BaseModel):
    """Request payload for dynamically configuring the seam screening policy."""

    threshold: float = Field(default=0.5, ge=0.0, le=1.0, description="Threat detection score threshold.")
    timeout_seconds: float = Field(default=4.0, ge=0.1, le=30.0, description="Timeout before local fallback.")
    max_chunk_chars: int = Field(default=1200, ge=100, le=5000, description="Max character slice per unit.")
    fast_model_enabled: bool = Field(default=True, description="Enable micro-model scoring.")
    fail_open_on_error: bool = True


class SeamScreeningMetricsResponse(BaseModel):
    """Operational security telemetry and screening gateway metrics."""

    total_requests: int = Field(..., ge=0, description="Total seam screen operations evaluated.")
    clean_verdicts: int = Field(..., ge=0, description="Total clean outputs passed untouched.")
    redacted_verdicts: int = Field(..., ge=0, description="Total outputs where injections were redacted.")
    fail_open_verdicts: int = Field(..., ge=0, description="Total executions degraded via fail-open safety.")
    avg_latency_ms: float = Field(..., ge=0.0, description="Average screening latency in milliseconds.")
    total_flagged_units: int = Field(..., ge=0, description="Cumulative count of malicious units erased.")
