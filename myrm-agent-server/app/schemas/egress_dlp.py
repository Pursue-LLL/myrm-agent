"""Pydantic DTO schemas for Agent Egress Telemetry Scraper & Enterprise DLP Guard.

[INPUT]
- None.

[OUTPUT]
- Typed DTO models for network egress rules, telemetry signatures, dependency scans,
  and DLP validation reports.

[POS]
- Server schemas. Exposes typed contracts for enterprise outbound traffic inspection and DLP.
"""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict, Field


class EgressRuleDto(BaseModel):
    """Network egress rule declaration DTO."""

    model_config = ConfigDict(extra="forbid")

    destination: str = Field(..., description="Target domain, IP address, or URL endpoint")
    port: int | None = Field(default=None, description="Destination network port (e.g. 443)")
    protocol: str = Field(default="tcp", description="Network protocol: tcp, udp, https")
    description: str = Field(default="", description="Rule description or business justification")


class TelemetrySignatureDto(BaseModel):
    """Known telemetry collection service signature DTO."""

    model_config = ConfigDict(extra="forbid")

    target_domain: str = Field(..., description="Prohibited telemetry domain suffix")
    framework_name: str = Field(..., description="Third-party framework or analytics provider name")
    risk_level: str = Field(..., description="Severity classification: LOW, MEDIUM, HIGH, CRITICAL")
    description: str = Field(..., description="Contextual description of data collected by this endpoint")


class DLPScanResultDto(BaseModel):
    """Verdict and inspection report generated by the DLP scanner."""

    model_config = ConfigDict(extra="forbid")

    is_safe: bool = Field(..., description="True if no telemetry leaks or evasions were found")
    verdict: str = Field(..., description="ALLOWED, BLOCKED_TELEMETRY_DOMAIN, etc.")
    detected_signatures: list[TelemetrySignatureDto] = Field(
        default_factory=list, description="Telemetry signatures triggered by inspection"
    )
    detected_dependencies: list[str] = Field(
        default_factory=list, description="Prohibited telemetry tracking libraries detected"
    )
    offending_rules: list[EgressRuleDto] = Field(
        default_factory=list, description="Specific egress policy rules that were blocked"
    )
    audit_trail: str = Field(default="", description="Audit log explanation and reasoning")


class ValidateEgressPolicyRequest(BaseModel):
    """Request payload to validate a declared set of egress network rules."""

    model_config = ConfigDict(extra="forbid")

    rules: list[EgressRuleDto] = Field(..., description="List of declared outbound network egress rules")
    allowed_exceptions: list[str] = Field(
        default_factory=list, description="Approved exceptions/whitelisted domain hosts"
    )


class ScanDependenciesRequest(BaseModel):
    """Request payload to scan a package dependency manifest for telemetry tracking SDKs."""

    model_config = ConfigDict(extra="forbid")

    manifest_content: str = Field(
        ..., description="Raw text of requirements.txt or pyproject.toml dependencies"
    )


class ScanProjectRequest(BaseModel):
    """Request payload to inspect a local project directory for telemetry endpoints."""

    model_config = ConfigDict(extra="forbid")

    project_dir: str = Field(..., description="Absolute path to project directory to scan")
