"""Storage key layout type definitions


[INPUT]
- enum::Enum (POS: Python enum type)

[OUTPUT]
- FilePurpose: file purpose enum (UPLOAD, GENERATED, SKILL)
- SkillType: skill type enum (PREBUILT, LOCAL, WORKSPACE)

[POS]
Business storage-key vocabulary. FilePurpose and SkillType determine where files and skills live
under the StorageProvider root (key layout: files/{purpose}/..., skills/{type}/...).
Single source of truth for the server's file and skill services; the harness StorageProvider stays key-agnostic.
"""

from __future__ import annotations

from enum import StrEnum


class FilePurpose(StrEnum):
    """File purpose; determines the storage path.

    Storage path format: files/{purpose}/{file_id}

    Attributes:
        UPLOAD: Files uploaded by the user (input files)
        GENERATED: Files generated by skills (output files)
        SKILL: Skill package content
    """

    UPLOAD = "upload"
    GENERATED = "generated"
    SKILL = "skill"


class SkillType(StrEnum):
    """Skill type determines storage path: skills/{type}/{skill_id}

    Attributes:
        PREBUILT: Admin-managed built-in skills
        LOCAL: Filesystem skills scanned from user-configured paths
        WORKSPACE: Project-level skills discovered in working directory
    """

    PREBUILT = "prebuilt"
    LOCAL = "local"
    WORKSPACE = "workspace"


__all__ = [
    "FilePurpose",
    "SkillType",
]
